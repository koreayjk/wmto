-- ───────── 한 챕터에 같은 업종은 한 명 (데이터베이스가 직접 보장) ─────────
create or replace function enforce_category_exclusive() returns trigger
language plpgsql security definer set search_path = wmto as $$
declare mid uuid; cid int; ch uuid; clash text;
begin
  if tg_table_name = 'mentor_profiles' then
    mid := new.member_id; cid := new.category_id;
    select chapter_id into ch from members where id = mid and role = 'mentor' and status = 'active';
  else -- members
    mid := new.id; ch := new.chapter_id;
    if new.role <> 'mentor' or new.status <> 'active' then return new; end if;
    select category_id into cid from mentor_profiles where member_id = mid;
  end if;
  if cid is null or ch is null then return new; end if;
  select m.name into clash from members m join mentor_profiles p on p.member_id = m.id
   where m.chapter_id = ch and m.role = 'mentor' and m.status = 'active' and p.category_id = cid and m.id <> mid limit 1;
  if clash is not null then
    raise exception 'category_taken: % 님이 같은 챕터에서 이 업종을 이미 맡고 있습니다', clash using errcode = 'unique_violation';
  end if;
  return new;
end $$;
drop trigger if exists mentor_profiles_category_exclusive on mentor_profiles;
create trigger mentor_profiles_category_exclusive before insert or update of category_id on mentor_profiles
  for each row execute function enforce_category_exclusive();
drop trigger if exists members_category_exclusive on members;
create trigger members_category_exclusive before update of chapter_id, status, role on members
  for each row execute function enforce_category_exclusive();

-- ───────── 챕터 자동 배정 변경: 업종이 비어 있고 50명 미만인 같은 지역 챕터로, 없으면 새 챕터 ─────────
create or replace function assign_member_tent(p_member uuid) returns void
language plpgsql security definer set search_path = wmto as $$
declare
  m members; kk record; t chapters; cid int; n int;
begin
  select * into m from members where id = p_member;
  if not found or m.role not in ('mentor', 'sponsor') or m.status <> 'active' then return; end if;
  select * into kk from tent_key(m.country, m.region, m.email like '%@demo.wmto.invalid');
  if kk.k is null then return; end if;
  select category_id into cid from mentor_profiles where member_id = m.id;

  if m.role = 'mentor' then
    select c.* into t from chapters c
     where c.region_key = kk.k
       and (select count(*) from members x where x.chapter_id = c.id and x.role = 'mentor' and x.status = 'active' and x.id <> m.id) < tent_cap()
       and (cid is null or not exists (
             select 1 from members x join mentor_profiles p on p.member_id = x.id
              where x.chapter_id = c.id and x.role = 'mentor' and x.status = 'active' and x.id <> m.id and p.category_id = cid))
     order by (m.district is not null and m.district = any (c.districts)) desc, c.seq limit 1;
  else
    select c.* into t from chapters c where c.region_key = kk.k
     order by (m.district is not null and m.district = any (c.districts)) desc, c.seq limit 1;
  end if;

  if not found then
    select count(*) into n from chapters where region_key = kk.k;
    insert into chapters (name, region, region_key, base, seq)
    values (case when n = 0 then kk.base || ' 텐트' else kk.base || ' ' || (n + 1) || '텐트' end, kk.grp, kk.k, kk.base, n + 1)
    returning * into t;
    if n = 1 then -- 두 번째 챕터가 생기면 첫 챕터 이름에도 번호를 붙임
      update chapters set name = base || ' 1텐트' where region_key = kk.k and seq = 1;
      update members x set chapter = c.name from chapters c where c.id = x.chapter_id and c.region_key = kk.k;
    end if;
  end if;
  if m.district is not null and not (m.district = any (t.districts)) then
    update chapters set districts = array_append(districts, m.district) where id = t.id;
  end if;
  update members set chapter_id = t.id, chapter = t.name where id = m.id;
end $$;
revoke all on function assign_member_tent(uuid) from public, anon, authenticated;

