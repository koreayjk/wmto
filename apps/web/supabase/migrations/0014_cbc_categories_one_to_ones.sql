-- 1:1 기록 만들기 (사업가 회원 → 같은 챕터의 사업가)
create or replace function create_one_to_one(
  p_other uuid, p_held_at timestamptz, p_place text, p_duration int,
  p_learned text, p_can_help text, p_next text, p_intro text, p_prayer text,
  p_proof_path text, p_consent boolean
) returns uuid language plpgsql security definer set search_path = wmto as $$
declare me uuid := current_member_id(); new_id uuid; ok boolean;
begin
  if request_view_as() is not null then raise exception 'view only'; end if;
  if me is null or current_member_role() <> 'mentor' then raise exception 'forbidden'; end if;
  select exists (select 1 from members a, members b where a.id = me and b.id = p_other and b.role = 'mentor' and b.status = 'active'
                 and a.chapter_id is not null and a.chapter_id = b.chapter_id) into ok;
  if not ok then raise exception 'not in same chapter'; end if;
  if p_held_at > now() + interval '1 hour' then raise exception 'future date'; end if;
  if coalesce(btrim(p_learned), '') = '' or coalesce(btrim(p_can_help), '') = '' or coalesce(btrim(p_next), '') = '' then raise exception 'form incomplete'; end if;
  insert into one_to_ones (member_a, member_b, held_at, place, duration_min, learned, can_help, next_step, intro_to, prayer, proof_path, consent_a)
  values (me, p_other, p_held_at, nullif(btrim(p_place), ''), p_duration, left(btrim(p_learned), 2000), left(btrim(p_can_help), 2000), left(btrim(p_next), 2000),
          nullif(left(btrim(coalesce(p_intro, '')), 1000), ''), nullif(left(btrim(coalesce(p_prayer, '')), 1000), ''), p_proof_path, coalesce(p_consent, false))
  returning id into new_id;
  return new_id;
end $$;

-- 상대가 확인 (같은 쌍은 30일에 1회만 인정)
create or replace function confirm_one_to_one(p_id uuid, p_consent boolean) returns void
language plpgsql security definer set search_path = wmto as $$
declare me uuid := current_member_id(); r one_to_ones;
begin
  if request_view_as() is not null then raise exception 'view only'; end if;
  select * into r from one_to_ones where id = p_id for update;
  if not found or r.member_b <> me then raise exception 'forbidden'; end if;
  if r.status <> 'pending' then raise exception 'already decided'; end if;
  if r.expires_at < now() then raise exception 'expired'; end if;
  if exists (select 1 from one_to_ones o where o.status = 'confirmed' and o.id <> r.id
              and least(o.member_a, o.member_b) = least(r.member_a, r.member_b) and greatest(o.member_a, o.member_b) = greatest(r.member_a, r.member_b)
              and abs(extract(epoch from (o.held_at - r.held_at))) < 30 * 86400) then
    raise exception 'duplicate within 30 days';
  end if;
  update one_to_ones set status = 'confirmed', confirmed_at = now(), consent_b = coalesce(p_consent, false) where id = p_id;
end $$;

create or replace function decline_one_to_one(p_id uuid) returns void
language plpgsql security definer set search_path = wmto as $$
begin
  if request_view_as() is not null then raise exception 'view only'; end if;
  update one_to_ones set status = 'declined' where id = p_id and member_b = current_member_id() and status = 'pending';
end $$;

-- 같은 챕터 회원 목록과 "이미 만났는가"(최근 90일 확인된 1:1)
create or replace function chapter_peers() returns table (
  id uuid, name text, photo_url text, business_name text, category_name text, last_met timestamptz, met_90d boolean
) language sql stable security definer set search_path = wmto as $$
  select b.id, b.name, b.photo_url, mp.business_name, c.name_ko,
         (select max(o.held_at) from one_to_ones o where o.status = 'confirmed' and ((o.member_a = me.id and o.member_b = b.id) or (o.member_b = me.id and o.member_a = b.id))),
         exists (select 1 from one_to_ones o where o.status = 'confirmed' and o.held_at > now() - interval '90 days' and ((o.member_a = me.id and o.member_b = b.id) or (o.member_b = me.id and o.member_a = b.id)))
  from members me
  join members b on b.chapter_id = me.chapter_id and b.role = 'mentor' and b.status = 'active' and b.id <> me.id
  left join mentor_profiles mp on mp.member_id = b.id
  left join industry_categories c on c.id = mp.category_id
  where me.id = current_member_id() and current_member_role() = 'mentor'
  order by b.name;
$$;

